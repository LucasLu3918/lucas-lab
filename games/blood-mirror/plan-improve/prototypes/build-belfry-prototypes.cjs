// Builds the single-file prototypes e1-pendulum.html and e1-starwheel.html from the shipped modules, so a prototype and the
// game run the very same rules and interface. Run: node build-belfry-prototypes.cjs   (then node ../../../../scripts/... tests are unchanged)
// Each page strips the ES-module syntax from puzzles/clock.js, belfry-hints.js and one mechanism, inlines challenges.css and the
// stage banner, and stands in for the game's puzzle window with a small stub (render, done, playCue). Zero dependencies, opens from disk.
const fs=require('fs'),path=require('path');
const game=path.join(__dirname,'..','..');
const read=file=>fs.readFileSync(path.join(game,file),'utf8');
const strip=source=>source.replace(/^import .*$/gm,'').replace(/^export (const|function|let)/gm,'$1');
const pages=[
 {out:'e1-pendulum.html',title:'E1 鐘擺 原型',module:'puzzles/pendulum.js',mount:'mountPendulum',banner:'assets/puzzles/belfry-pendulum.webp',stage:'ABYSS · 鐘擺'},
 {out:'e1-starwheel.html',title:'E1 星輪 原型',module:'puzzles/starwheel.js',mount:'mountStarWheel',banner:'assets/puzzles/belfry-wheel.webp',stage:'ABYSS · 星輪'}
];
for(const page of pages){
 const banner='data:image/webp;base64,'+fs.readFileSync(path.join(game,page.banner)).toString('base64');
 const code=[strip(read('puzzles/clock.js')),strip(read('puzzles/belfry-hints.js')),strip(read(page.module))].join('\n');
 const html='<!doctype html>\n<html lang="zh-Hant"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">\n'
  +'<title>'+page.title+'</title>\n'
  +'<!-- Prototype generated by build-belfry-prototypes.cjs from the shipped modules (puzzles/'+path.basename(page.module)+'). Not shipped. -->\n'
  +'<style>:root{--serif:"Noto Serif TC","Songti TC",Georgia,serif;--sans:"Noto Sans TC","PingFang TC",system-ui,sans-serif;--gold:#c3ac80;--line:rgba(195,172,128,.19)}'
  +'*{box-sizing:border-box}body{margin:0;background:#100f10;color:#eee5d6;font:14px/1.8 var(--sans)}button{min-height:44px;font:inherit;cursor:pointer;color:inherit;border:0;background:none}'
  +'#modal{max-width:640px;margin:16px auto;padding:24px 32px;border:1px solid #bc9f6740;border-radius:12px;background:#191619}'
  +'.secondary-button{border:1px solid var(--line);padding:12px;color:var(--gold)}.primary-button{background:#8d2d3b;border:1px solid #ac4e4b66;color:#f4e9dc;padding:12px 24px;width:100%;margin-top:12px}'
  +'.modal-text,h2{font-family:var(--serif)}#proto-done{display:none;padding:16px;border:1px solid #7fd08a;color:#bfeac5;margin-top:12px}'
  +read('challenges.css')+'</style></head><body>\n'
  +'<div id="modal"><h2>逆走鐘樓</h2><p class="belfry-note">'+page.stage+' · 原型（規則與介面與遊戲相同）</p><div id="host" class="challenge"></div><p id="proto-done" role="status"></p></div>\n'
  +'<script>\n'+code+'\n'
  +'const host=document.getElementById("host");\n'
  +'const banner=\'<img class="stage-art" src="'+banner+'" alt="" width="960" height="411">\';\n'
  +page.mount+'({render(html){host.innerHTML=banner+html;},feedback(){},playCue(){},done(){const d=document.getElementById("proto-done");d.style.display="block";d.textContent="這一道機關完成了。（正式遊戲會在這裡進入下一道。）";}});\n'
  +'</script></body></html>\n';
 fs.writeFileSync(path.join(__dirname,page.out),html);
 console.log('wrote',page.out,Math.round(html.length/1024)+' KB');
}
